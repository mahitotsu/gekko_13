// サービスの状態の置き場所（段 D の D1-a3。判断 53〜55）。2 つのタスクが同じ状態を読むよう、共有のデータベース（AWS では Aurora）に置く。
// 顧客のアプリ（セッション、ログインの途中の情報、受信箱）と、営業 AI エージェント（会話）が使う。
// - キーは、Cookie の値や会話の ID の SHA-256 にする（データベースが漏れても、セッションを乗っ取れない）。
// - 暗号鍵（STATE_KEY、16 進で 32 バイト）を渡したときは、中身を AES-256-GCM で暗号化し、種類とキーを付加データにする
//   （データベースだけが漏れても、暗号文しか出ない。行を別のキーへ写しても、復号できない）。顧客のアプリは必ず渡す（判断 54）。
//   AWS では aws/deploy.sh が一度だけ作って SSM に置き、ECS が渡す。
// - 受信箱: 保険会社のシステムからの直送と、画面の読み取りが、別のタスクに当たるので、同じく共有のデータベースに置く。
// 試験では、メモリの実装（memoryState）を使う。
import { createCipheriv, createDecipheriv, createHash, randomBytes } from "node:crypto";
import { readFileSync } from "node:fs";
import pg from "pg";

/** 状態の種類。session はログイン中のセッション、login はログインの途中（認可コードを受け取るまで）、conversation は営業 AI エージェントの会話。 */
export type Kind = "session" | "login" | "conversation";

export interface StateStore {
  /** 1 件を読む。なければ、または期限を過ぎていれば undefined。 */
  get(kind: Kind, id: string): Promise<string | undefined>;
  /** 1 件を書く。期限（ミリ秒の時刻）を過ぎたものは、読めなくなる。 */
  put(kind: Kind, id: string, value: string, expiresAt: number): Promise<void>;
  /** 1 件を読んで消す。2 つのタスクが同時に読んでも、渡すのは片方だけ（ログインの途中は 1 回だけ使う）。 */
  take(kind: Kind, id: string): Promise<string | undefined>;
  delete(kind: Kind, id: string): Promise<void>;
  /**
   * 1 件をロックして読み、fn の結果を書き戻す。ほかのタスクの同じ件の locked は、終わるまで待つ（トークンの更新を 1 つのタスクだけが行う）。
   * fn が undefined を返したら、書き戻さない。
   */
  locked<T>(kind: Kind, id: string, fn: (value: string | undefined) => Promise<{ value?: string; expiresAt?: number; result: T }>): Promise<T>;
  addNotice(inbox: string, notice: string): Promise<void>;
  notices(inbox: string): Promise<string[]>;
}

/** Cookie の値は、そのまま置かず、SHA-256 にする（データベースが漏れても、セッションを乗っ取れない）。 */
const keyOf = (id: string) => createHash("sha256").update(id).digest("base64url");

/** 暗号化と復号。付加データに、種類とキーを入れる。 */
export function sealer(hexKey: string) {
  const key = Buffer.from(hexKey, "hex");
  if (key.length !== 32) throw new Error("STATE_KEY は 16 進で 32 バイト");
  return {
    seal(aad: string, plain: string): string {
      const iv = randomBytes(12);
      const c = createCipheriv("aes-256-gcm", key, iv).setAAD(Buffer.from(aad));
      const body = Buffer.concat([c.update(plain, "utf8"), c.final()]);
      return Buffer.concat([iv, c.getAuthTag(), body]).toString("base64url");
    },
    open(aad: string, sealed: string): string {
      const raw = Buffer.from(sealed, "base64url");
      const d = createDecipheriv("aes-256-gcm", key, raw.subarray(0, 12)).setAAD(Buffer.from(aad));
      d.setAuthTag(raw.subarray(12, 28));
      return Buffer.concat([d.update(raw.subarray(28)), d.final()]).toString("utf8");
    },
  };
}

/** 試験のための、メモリの実装。暗号化はしない。 */
export function memoryState(): StateStore {
  const rows = new Map<string, { value: string; expiresAt: number }>();
  const inbox = new Map<string, string[]>();
  const locks = new Map<string, Promise<unknown>>();
  const k = (kind: Kind, id: string) => `${kind}:${keyOf(id)}`;
  const read = (key: string) => {
    const row = rows.get(key);
    if (row && row.expiresAt < Date.now()) rows.delete(key);
    return rows.get(key)?.value;
  };
  return {
    get: async (kind, id) => read(k(kind, id)),
    put: async (kind, id, value, expiresAt) => void rows.set(k(kind, id), { value, expiresAt }),
    take: async (kind, id) => {
      const v = read(k(kind, id));
      rows.delete(k(kind, id));
      return v;
    },
    delete: async (kind, id) => void rows.delete(k(kind, id)),
    locked: async (kind, id, fn) => {
      const key = k(kind, id);
      const before = locks.get(key) ?? Promise.resolve();
      const run = before.catch(() => undefined).then(async () => {
        const out = await fn(read(key));
        const row = rows.get(key);
        if (out.value !== undefined) rows.set(key, { value: out.value, expiresAt: out.expiresAt ?? row?.expiresAt ?? 0 });
        return out.result;
      });
      locks.set(key, run);
      return run;
    },
    addNotice: async (box, notice) => void inbox.set(box, [...(inbox.get(box) ?? []), notice]),
    notices: async (box) => inbox.get(box) ?? [],
  };
}

const SCHEMA = `
SELECT pg_advisory_lock(7231003);
CREATE TABLE IF NOT EXISTS app_state (
  kind text NOT NULL,
  id text NOT NULL,
  sealed text NOT NULL,
  expires_at bigint NOT NULL,
  PRIMARY KEY (kind, id)
);
CREATE TABLE IF NOT EXISTS inbox_notice (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inbox text NOT NULL,
  notice text NOT NULL
);
CREATE INDEX IF NOT EXISTS inbox_notice_inbox ON inbox_notice (inbox);
SELECT pg_advisory_unlock(7231003);
`;

/**
 * 共有のデータベースの実装。環境変数: DB_URL（postgres://ホスト:ポート/データベース）、DB_USER、DB_PASSWORD、STATE_KEY。
 * DB_CA_PEM（Aurora の CA）があれば、TLS で Aurora の証明書と名前を確かめる。手元の PostgreSQL のコンテナでは、平文でつなぐ。
 */
export async function pgState(env: NodeJS.ProcessEnv = process.env, opts: { seal: boolean } = { seal: true }): Promise<StateStore> {
  const url = env.DB_URL;
  if (!url) throw new Error("環境変数 DB_URL がない（状態を共有のデータベースに置く。判断 53）");
  const plain = { seal: (_aad: string, v: string) => v, open: (_aad: string, v: string) => v };
  const box = opts.seal ? sealer(env.STATE_KEY ?? "") : plain;
  const ca = env.DB_CA_PEM ?? (env.DB_CA_FILE ? readFileSync(env.DB_CA_FILE, "utf8") : undefined);
  // 接続の文字列を渡すと、pg は、文字列にない利用者名も、文字列の側（空）で上書きする。宛先は、文字列から取り出して個別に渡す
  const target = new URL(url);
  const pool = new pg.Pool({
    host: target.hostname,
    port: Number(target.port || 5432),
    database: target.pathname.slice(1),
    user: env.DB_USER,
    password: env.DB_PASSWORD,
    max: 5,
    connectionTimeoutMillis: 10_000,
    ...(ca ? { ssl: { ca, rejectUnauthorized: true } } : {}),
  });
  await pool.query(SCHEMA);
  const aad = (kind: Kind, key: string) => `${kind}:${key}`;
  const open = (kind: Kind, key: string, row?: { sealed: string }) => (row ? box.open(aad(kind, key), row.sealed) : undefined);
  let swept = 0;
  const sweep = () => {
    if (Date.now() - swept < 60_000) return;
    swept = Date.now();
    void pool.query("DELETE FROM app_state WHERE expires_at < $1", [Date.now()]).catch(() => undefined);
  };
  return {
    async get(kind, id) {
      sweep();
      const key = keyOf(id);
      const r = await pool.query<{ sealed: string }>("SELECT sealed FROM app_state WHERE kind = $1 AND id = $2 AND expires_at >= $3", [kind, key, Date.now()]);
      return open(kind, key, r.rows[0]);
    },
    async put(kind, id, value, expiresAt) {
      const key = keyOf(id);
      await pool.query(
        "INSERT INTO app_state (kind, id, sealed, expires_at) VALUES ($1, $2, $3, $4) ON CONFLICT (kind, id) DO UPDATE SET sealed = EXCLUDED.sealed, expires_at = EXCLUDED.expires_at",
        [kind, key, box.seal(aad(kind, key), value), expiresAt],
      );
    },
    async take(kind, id) {
      const key = keyOf(id);
      const r = await pool.query<{ sealed: string; expires_at: string }>("DELETE FROM app_state WHERE kind = $1 AND id = $2 RETURNING sealed, expires_at", [kind, key]);
      const row = r.rows[0];
      return row && Number(row.expires_at) >= Date.now() ? open(kind, key, row) : undefined;
    },
    async delete(kind, id) {
      await pool.query("DELETE FROM app_state WHERE kind = $1 AND id = $2", [kind, keyOf(id)]);
    },
    async locked(kind, id, fn) {
      const key = keyOf(id);
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const r = await client.query<{ sealed: string }>("SELECT sealed FROM app_state WHERE kind = $1 AND id = $2 AND expires_at >= $3 FOR UPDATE", [kind, key, Date.now()]);
        const out = await fn(open(kind, key, r.rows[0]));
        if (out.value !== undefined) {
          await client.query(
            "INSERT INTO app_state (kind, id, sealed, expires_at) VALUES ($1, $2, $3, $4) ON CONFLICT (kind, id) DO UPDATE SET sealed = EXCLUDED.sealed, expires_at = COALESCE($5, app_state.expires_at)",
            [kind, key, box.seal(aad(kind, key), out.value), out.expiresAt ?? 0, out.expiresAt ?? null],
          );
        }
        await client.query("COMMIT");
        return out.result;
      } catch (e) {
        await client.query("ROLLBACK").catch(() => undefined);
        throw e;
      } finally {
        client.release();
      }
    },
    async addNotice(inbox, notice) {
      await pool.query("INSERT INTO inbox_notice (inbox, notice) VALUES ($1, $2)", [inbox, notice]);
    },
    async notices(inbox) {
      const r = await pool.query<{ notice: string }>("SELECT notice FROM inbox_notice WHERE inbox = $1 ORDER BY id", [inbox]);
      return r.rows.map((row) => row.notice);
    },
  };
}

/** 動いている置き場所。各サービスの main.ts が起動のときに pgState を渡す。試験では、渡さなければメモリの実装になる。 */
let store: StateStore = memoryState();
export const useState = (s: StateStore) => (store = s);
export const state = () => store;
