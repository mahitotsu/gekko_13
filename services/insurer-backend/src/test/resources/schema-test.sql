-- 試験の表。src/main/resources/schema.sql から、PostgreSQL だけのアドバイザリーロックを除いたもの（同じ変更で直す）
-- 保険会社のシステムの表（段 D の D1-a3。判断 53）。提示の nonce、契約の記録、送り出しの記録。なければ作る。
-- 2 つのタスクが同時に起きても、表を 1 回だけ作るように、アドバイザリーロックで順番にする（同じ接続で流れる）
-- 提示に付けた nonce（gekko_11 の G16）。申込みで、未使用で期限内のときだけ、使用済みにする
CREATE TABLE IF NOT EXISTS offer_nonce (
    nonce varchar(64) NOT NULL PRIMARY KEY,
    customer varchar(200) NOT NULL,
    expires_at bigint NOT NULL,
    used boolean NOT NULL
);
-- 契約の記録（gekko_11 の D-9）。入れ子の値は JSON の文字列。id は記録した順
CREATE TABLE IF NOT EXISTS contract_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract text NOT NULL,
    act_chain text NOT NULL,
    at_epoch bigint NOT NULL,
    application text NOT NULL,
    intent text NOT NULL,
    token_jti text
);
-- 提出の冪等（段 D の D1-a3）。同じ nonce の、同じ署名済みの申込みの 2 度目には、この契約を返す。前からある行は NULL
ALTER TABLE contract_record ADD COLUMN IF NOT EXISTS nonce varchar(64);
-- 直送の記録（gekko_11 の P-8）。届いたかどうかと一緒に残す
CREATE TABLE IF NOT EXISTS delivery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient text NOT NULL,
    notice text NOT NULL,
    delivered boolean NOT NULL
);
-- 送り直し（段 D の D1-a3）。試した回数、次に試す時刻（UNIX ミリ秒。送り直さないときは NULL）、最後の誤り。前からある行は送り直さない
ALTER TABLE delivery ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 1;
ALTER TABLE delivery ADD COLUMN IF NOT EXISTS next_at bigint;
ALTER TABLE delivery ADD COLUMN IF NOT EXISTS last_error text;
