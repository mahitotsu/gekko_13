-- 提示に付けた nonce（gekko_11 の G16）。申込みで、未使用で期限内のときだけ、使用済みにする
CREATE TABLE IF NOT EXISTS offer_nonce (
    nonce varchar(64) NOT NULL PRIMARY KEY,
    customer varchar(200) NOT NULL,
    expires_at bigint NOT NULL,
    used boolean NOT NULL
);
-- 契約の記録（gekko_11 の D-9）。入れ子の値は JSON の文字列。id は記録した順
CREATE TABLE IF NOT EXISTS contract_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract text NOT NULL,
    act_chain text NOT NULL,
    at_epoch bigint NOT NULL,
    application text NOT NULL,
    intent text NOT NULL,
    token_jti text
);
-- 直送の記録（gekko_11 の P-8）。届いたかどうかと一緒に残す
CREATE TABLE IF NOT EXISTS delivery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient text NOT NULL,
    notice text NOT NULL,
    delivered boolean NOT NULL
);
